import Testing
@testable import ScreenVoice

@Suite("Spoken text")
struct SpokenTextNormalizerTests {
    private func spoken(_ text: String) -> String { SpokenTextNormalizer.normalize(text) }

    @Test func spellsCardinalsInEveryCase() {
        typealias N = RussianNumerals
        #expect(N.cardinal(0) == "ноль")
        #expect(N.cardinal(1500) == "тысяча пятьсот")
        #expect(N.cardinal(21, gender: .feminine) == "двадцать одна")
        #expect(N.cardinal(2, gender: .feminine) == "две")
        #expect(N.cardinal(2_002_000) == "два миллиона две тысячи")
        #expect(N.cardinal(1_000_000) == "миллион")
        #expect(N.cardinal(5000, case: .genitive) == "пяти тысяч")
        #expect(N.cardinal(1000, case: .accusative) == "тысячу")
        #expect(N.cardinal(342, case: .instrumental) == "тремястами сорока двумя")
        #expect(N.cardinal(84, case: .dative) == "восьмидесяти четырём")
        #expect(N.cardinal(21, gender: .feminine, case: .genitive) == "двадцати одной")
        #expect(N.digits("0199") == "ноль один девять девять")
    }

    @Test func spellsOrdinals() {
        typealias N = RussianNumerals
        #expect(N.ordinal(1984, case: .prepositional) == "тысяча девятьсот восемьдесят четвёртом")
        #expect(N.ordinal(2000, case: .genitive) == "двухтысячного")
        #expect(N.ordinal(2024, case: .genitive) == "две тысячи двадцать четвёртого")
        #expect(N.ordinal(3, gender: .feminine) == "третья")
        #expect(N.ordinal(3, case: .genitive) == "третьего")
        #expect(N.ordinal(40) == "сороковой")
        #expect(N.ordinal(90, plural: true, case: .genitive) == "девяностых")
        #expect(N.ordinal(1900) == "тысяча девятисотый")
        #expect(N.ordinal(21, gender: .feminine) == "двадцать первая")
        #expect(N.roman("XIV") == 14)
        #expect(N.roman("XX") == 20)
        #expect(N.compoundPrefix(25) == "двадцатипяти")
        #expect(N.compoundPrefix(1) == "одно")
        #expect(N.compoundPrefix(90) == "девяносто")
    }

    @Test func leavesOrdinaryTextAlone() {
        for text in ["Привет, как дела?", "Он сказал: «Нет». И ушёл...", "Позвони в МЧС.", "Агент ФБР прибыл из США.",
                     "Позвони мне на iPhone, я в New York.", "John Smith работает в Google.", "Что-то не так - уходим!",
                     "Кто-то из-за угла.", "Смотри  сюда .", ""] {
            #expect(spoken(text) == text)
        }
    }

    @Test func readsNumbersWithTheirNouns() {
        #expect(spoken("У нас осталось всего 3 патрона и 2 литра воды.") == "У нас осталось всего три патрона и два литра воды.")
        #expect(spoken("Ему 21 год, а ей 32 года.") == "Ему двадцать один год, а ей тридцать два года.")
        #expect(spoken("Буду через 5 минут или через 1 час.") == "Буду через пять минут или через один час.")
        #expect(spoken("Осталось 100 метров и 1 секунда.") == "Осталось сто метров и одна секунда.")
        #expect(spoken("Жди 1 минуту, потом 2 минуты.") == "Жди одну минуту, потом две минуты.")
        #expect(spoken("Экипаж из 1000 человек.") == "Экипаж из тысячи человек.")
        #expect(spoken("Это в 2 раза больше.") == "Это в два раза больше.")
        #expect(spoken("С 5 до 7 вечера.") == "С пяти до семи вечера.")
        #expect(spoken("Около 20 человек, не больше 30.") == "Около двадцати человек, не больше тридцати.")
        #expect(spoken("Он пришёл с 3 друзьями.") == "Он пришёл с тремя друзьями.")
        #expect(spoken("В 5 метрах от нас.") == "В пяти метрах от нас.")
        #expect(spoken("К 6 часам вернусь.") == "К шести часам вернусь.")
        #expect(spoken("Здесь 1 500 человек и 10,000 птиц.") == "Здесь тысяча пятьсот человек и десять тысяч птиц.")
        #expect(spoken("5-7 минут.") == "Пять-семь минут.")
        #expect(spoken("Мой номер 555-0199.") == "Мой номер пятьсот пятьдесят пять-ноль один девять девять.")
        #expect(spoken("Счёт 3:2 в нашу пользу.") == "Счёт три два в нашу пользу.")
        #expect(spoken("iPhone 15 и 4K.") == "iPhone пятнадцать и 4K.")
    }

    @Test func readsDatesAndTimes() {
        #expect(spoken("Встреча назначена на 15 марта 2024 года в 9:30.")
            == "Встреча назначена на пятнадцатое марта две тысячи двадцать четвёртого года в девять тридцать.")
        #expect(spoken("Он родился в 1984 году.") == "Он родился в тысяча девятьсот восемьдесят четвёртом году.")
        #expect(spoken("1 января 2000 года всё изменилось.") == "Первого января двухтысячного года всё изменилось.")
        #expect(spoken("Это больше, чем в 2019.") == "Это больше, чем в две тысячи девятнадцатом.")
        #expect(spoken("Сегодня 5 мая 2021.") == "Сегодня пятое мая две тысячи двадцать первого года.")
        #expect(spoken("Письмо от 15.03.2024.") == "Письмо от пятнадцатого марта две тысячи двадцать четвёртого года.")
        #expect(spoken("Поезд отправляется в 18:05.") == "Поезд отправляется в восемнадцать ноль пять.")
        #expect(spoken("Жду тебя в 7:00, а не в 1:00.") == "Жду тебя в семь часов, а не в час.")
        #expect(spoken("Это было в 90-х годах XX века.") == "Это было в девяностых годах двадцатого века.")
        #expect(spoken("Война началась в XIX в.") == "Война началась в девятнадцатом веке.")
        #expect(spoken("В 1812 г. была война.") == "В тысяча восемьсот двенадцатом году была война.")
        #expect(spoken("Глава 21. Возвращение.") == "Глава двадцать первая. Возвращение.")
        #expect(spoken("Эпизод IV") == "Эпизод четвёртый")
    }

    @Test func readsOrdinalEndingsAndCompounds() {
        #expect(spoken("Мы на 5-м этаже.") == "Мы на пятом этаже.")
        #expect(spoken("Он на 2-м месте после 3-го тайма.") == "Он на втором месте после третьего тайма.")
        #expect(spoken("Это 1-й раз, 2-я попытка и 3-е окно.") == "Это первый раз, вторая попытка и третье окно.")
        #expect(spoken("Лихие 90-е.") == "Лихие девяностые.")
        #expect(spoken("В 3-х шагах, из 5-ти человек.") == "В трёх шагах, из пяти человек.")
        #expect(spoken("5-летний план и 3-комнатная квартира.") == "Пятилетний план и трёхкомнатная квартира.")
    }

    @Test func readsMoneyUnitsAndSymbols() {
        #expect(spoken("Цена выросла на 25%, теперь это 1500 рублей.") == "Цена выросла на двадцать пять процентов, теперь это тысяча пятьсот рублей.")
        #expect(spoken("Это стоит 1500 руб.") == "Это стоит тысячу пятьсот рублей.")
        #expect(spoken("Дай 100 руб. и уходи.") == "Дай сто рублей и уходи.")
        #expect(spoken("Мне нужно $200 прямо сейчас.") == "Мне нужно двести долларов прямо сейчас.")
        #expect(spoken("Он должен мне 3 млн долларов.") == "Он должен мне три миллиона долларов.")
        #expect(spoken("Бюджет $1,5 млн, а не 5 тыс. руб.") == "Бюджет полтора миллиона долларов, а не пять тысяч рублей.")
        #expect(spoken("С вас $9.99.") == "С вас девять долларов девяносто девять центов.")
        #expect(spoken("До города 12 км, идти 2 ч.") == "До города двенадцать километров, идти два часа.")
        #expect(spoken("Температура упала до -15°C.") == "Температура упала до минус пятнадцати градусов Цельсия.")
        #expect(spoken("Вес посылки 2,5 кг.") == "Вес посылки два с половиной килограмма.")
        #expect(spoken("Купи 1,5 л молока и 300 г сыра.") == "Купи полтора литра молока и триста граммов сыра.")
        #expect(spoken("Скорость 120 км/ч.") == "Скорость сто двадцать километров в час.")
        #expect(spoken("Рост 1 м 80 см, вес 80 кг.") == "Рост один метр восемьдесят сантиметров, вес восемьдесят килограммов.")
        #expect(spoken("Буду через 1 мин.") == "Буду через одну минуту.")
        #expect(spoken("Число пи равно 3.14.") == "Число пи равно три целых четырнадцать сотых.")
        #expect(spoken("№ 7, 2+2=4, Том & Джерри.") == "Номер семь, два плюс два равно четыре, Том и Джерри.")
        #expect(spoken("-Привет. -15 человек.") == "-Привет. -Пятнадцать человек.")
    }

    @Test func readsAbbreviations() {
        #expect(spoken("Это доктор, т.е. врач, и т.д.") == "Это доктор, то есть врач, и так далее.")
        #expect(spoken("Яблоки, груши и т. п. Всё свежее.") == "Яблоки, груши и тому подобное. Всё свежее.")
        #expect(spoken("Г-н Смит и проф. Иванов.") == "Господин Смит и профессор Иванов.")
    }
}
